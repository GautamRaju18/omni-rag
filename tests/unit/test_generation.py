SAFETY = ("Cell AUR-C103 (electrolyte E-5) failed at cycle 412 during 45 °C cycling. "
          "The pouch swelled by 14% and vented without flame.")  # fmt: skip
BUDGET = ("| Workstream | Owner | Planned (EUR) |\n| --- | --- | --- |\n"
          "| Electrolyte | Marco Lindqvist | 240000 |")  # fmt: skip
FIGURE = ("Figure: Figure 1: Capacity retention per cell.\n"
          "Image description (generated by qwen3-vl:2b-instruct): A bar chart where all cells "
          "stay above 70% retention.")  # fmt: skip


def _block(i: int, text: str, file: str, pages: list[int] | None = None) -> ContextBlock:
    return ContextBlock(document_id=f"doc_{i}", source_file=file, section_path=["S"],
                        page_numbers=pages or [], chunk_ids=[f"c{i}"], hit_chunk_ids=[f"c{i}"],
                        element_ids=[f"e{i}"], origins=["original"], rank=i, text=text,
                        tokens=len(text.split()))  # fmt: skip


BLOCKS = [_block(1, SAFETY, "aurora_safety_review.pdf", [1]),
          _block(2, BUDGET, "aurora_budget_2026.xlsx"),
          _block(3, FIGURE, "aurora_status_report_2026-03.docx")]  # fmt: skip


def _context(blocks: list[ContextBlock] = BLOCKS) -> dict:
    ctx = AssembledContext(blocks=blocks, tokens=sum(b.tokens for b in blocks), budget_tokens=1024,
                           options=ContextOptions(), candidates=len(blocks))  # fmt: skip
    return {**ctx.model_dump(mode="json"), "rendered": ctx.render()}


# ---------------------------------------------------------------- citations
def test_verified_quote_in_a_cited_source() -> None:
    c = validate_claim({"text": "AUR-C103 failed at cycle 412.", "sources": [1],
                        "quote": "failed at cycle 412 during 45 °C cycling", "support": "direct"},
                       BLOCKS)  # fmt: skip
    assert (c.status, c.sources, c.support, c.issues) == ("verified", [1], "direct", [])


def test_quote_in_another_source_is_relocated_never_invented() -> None:
    c = validate_claim({"text": "Marco Lindqvist owns the electrolyte workstream.",
                        "sources": [1, 9], "quote": "| Electrolyte | Marco Lindqvist | 240000 |",
                        "support": "direct"}, BLOCKS)  # fmt: skip
    assert c.status == "relocated" and c.sources == [2]
    assert any("not in the context: [9]" in i for i in c.issues)


def test_a_changed_number_behind_a_true_quote_is_caught() -> None:
    c = validate_claim(
        {
            "text": "The pouch swelled by 15%.",
            "sources": [1],
            "quote": "The pouch swelled by 14%",
            "support": "direct",
        },
        BLOCKS,
    )
    assert c.status == "partial" and c.support == "inferred"
    assert any("[15.0]" in i for i in c.issues)


def test_paraphrase_without_quote_is_partial_and_fabrication_unsupported() -> None:
    para = validate_claim({"text": "The AUR-C103 pouch swelled 14% at cycle 412.", "sources": [1],
                           "quote": "it swelled a lot", "support": "direct"}, BLOCKS)  # fmt: skip
    assert para.status == "partial" and para.support == "inferred"
    made_up = validate_claim({"text": "AUR-C109 caught fire at cycle 900.", "sources": [1],
                              "quote": "caught fire", "support": "direct"}, BLOCKS)  # fmt: skip
    assert made_up.status == "unsupported"


def test_generated_image_text_makes_a_claim_inferred() -> None:
    c = validate_claim({"text": "All cells stay above 70% retention.", "sources": [3],
                        "quote": "all cells stay above 70% retention", "support": "direct"},
                       BLOCKS)  # fmt: skip
    assert c.status == "verified" and c.generated_evidence and c.support == "inferred"


def test_elided_table_quote_counts_only_within_one_line() -> None:
    """Measured: qwen3 quoted "Category: 300 | AUR-C106: 96.2", dropping the AUR-C105 column."""
    chart = _block(1, "Category: 300 | AUR-C105: 95.9 | AUR-C106: 96.2\n"
                      "Category: 400 | AUR-C105: 93.6 | AUR-C106: 94.1", "q1.pptx")  # fmt: skip
    c = validate_claim({"text": "AUR-C106 retained 96.2% after 300 cycles.", "sources": [1],
                        "quote": "Category: 300 | AUR-C106: 96.2", "support": "direct"},
                       [chart])  # fmt: skip
    assert c.status == "verified" and "quote leaves out parts of the source line" in c.issues
    across = validate_claim({"text": "AUR-C106 retained 94.1% after 300 cycles.", "sources": [1],
                             "quote": "Category: 300 | AUR-C106: 94.1", "support": "direct"},
                            [chart])  # fmt: skip
    assert across.status != "verified"  # parts from two different lines prove nothing


def test_text_also_in_ocr_is_original_evidence() -> None:
    board = _block(1, "Text in image (OCR, confidence 0.96): Pilot batch: 100 cells (M3)\n"
                      "Image description (generated by qwen3-vl:2b-instruct): The list includes "
                      "Pilot batch: 100 cells (M3).", "whiteboard.jpg")  # fmt: skip
    c = validate_claim(
        {
            "text": "The pilot batch is 100 cells.",
            "sources": [1],
            "quote": "Pilot batch: 100 cells (M3)",
            "support": "direct",
        },
        [board],
    )
    assert c.status == "verified" and not c.generated_evidence and c.support == "direct"


def test_numbers_ignore_identifier_digits_and_thousands_commas() -> None:
    assert numbers("AUR-C103 cost EUR 240,000 at 45 °C") == {240000.0, 45.0}


def test_validate_metrics_citations_and_rendered_answer() -> None:
    claims, citations, m = validate([
        {"text": "AUR-C103 failed at cycle 412", "sources": [1],
         "quote": "failed at cycle 412", "support": "direct"},
        {"text": "Planned electrolyte budget is EUR 240,000", "sources": [1],
         "quote": "| Electrolyte | Marco Lindqvist | 240000 |", "support": "direct"},
        {"text": "AUR-C103 was recalled in 2025", "sources": [1], "quote": "recalled",
         "support": "direct"},
    ], BLOCKS)  # fmt: skip
    assert [c.status for c in claims] == ["verified", "relocated", "unsupported"]
    assert [c.number for c in citations] == [1, 2]
    assert (m.claims, m.verified, m.relocated, m.unsupported) == (3, 1, 1, 1)
    assert m.citation_accuracy == pytest.approx(0.333) and m.faithfulness == pytest.approx(0.667)
    assert citations[0].page_numbers == [1] and citations[0].chunk_ids == ["c1"]
    text = render_answer(claims)
    assert text == ("AUR-C103 failed at cycle 412 [1]. Planned electrolyte budget is "
                    "EUR 240,000 [2].")  # fmt: skip
    assert "recalled" not in text


# ---------------------------------------------------------------- streaming parser
def test_claim_stream_yields_each_object_once_whatever_the_chunking() -> None:
    reply = json.dumps(
        {
            "answerable": True,
            "claims": [
                {
                    "text": 'a {brace} and "quote" ]',
                    "sources": [1],
                    "quote": "x",
                    "support": "direct",
                },
                {"text": "b", "sources": [2, 3], "quote": "y", "support": "inferred"},
            ],
            "missing": "",
        }
    )
    rng = random.Random(7)  # noqa: S311 - test chunking, not crypto
    for _ in range(20):
        parser, got, i = ClaimStream(), [], 0
        while i < len(reply):
            n = rng.randint(1, 9)
            got += parser.feed(reply[i : i + n])
            i += n
        assert [c["text"] for c in got] == ['a {brace} and "quote" ]', "b"]


# ---------------------------------------------------------------- generator
class GenLLM:
    model = "fake-model"

    def __init__(self, reply: dict | Exception) -> None:
        self.reply = reply
        self.calls = 0

    def chat(self, system, user, *, schema=None, **kw) -> ChatResult:
        assert system == ANSWER_SYSTEM and schema == ANSWER_SCHEMA
        assert user.startswith("Sources:\n\n[1] aurora_safety_review.pdf > S\n")
        self.calls += 1
        if isinstance(self.reply, Exception):
            raise self.reply
        return ChatResult(json.dumps(self.reply), self.reply, 40, 400, 12.0)

    def stream(self, system, user, *, schema=None, **kw):
        self.calls += 1
        text = json.dumps(self.reply)
        for i in range(0, len(text), 5):
            yield {"delta": text[i : i + 5]}
        yield {"done": True, "eval_tokens": 40, "prompt_tokens": 400, "ms": 12.0}


GOOD = {"answerable": True, "missing": "", "claims": [
    {"text": "AUR-C103 failed at cycle 412 at 45 °C.", "sources": [1],
     "quote": "failed at cycle 412 during 45 °C cycling", "support": "direct"},
    {"text": "Its pouch swelled by 14%.", "sources": [1],
     "quote": "The pouch swelled by 14%", "support": "direct"}]}  # fmt: skip


def test_generate_returns_a_grounded_cited_answer() -> None:
    llm = GenLLM(GOOD)
    a = AnswerGenerator(llm).generate("Why did AUR-C103 fail?", _context(), "sufficient")
    assert a.answerable and a.grounded and a.refused_by is None
    assert a.text == "AUR-C103 failed at cycle 412 at 45 °C [1]. Its pouch swelled by 14% [1]."
    assert [c.source_file for c in a.citations] == ["aurora_safety_review.pdf"]
    assert (a.metrics.faithfulness, a.prompt_tokens, a.model) == (1.0, 400, "fake-model")


def test_insufficient_check_refuses_without_a_model_call_unless_told_otherwise() -> None:
    llm = GenLLM(GOOD)
    gen = AnswerGenerator(llm)
    checks = [{"verdict": "insufficient", "missing_identifiers": ["AUR-C109"], "missing": ""}]
    a = gen.generate("What did AUR-C109 reach?", _context(), "insufficient", checks)
    assert (a.answerable, a.refused_by, a.missing, llm.calls) == (
        False, "check", "No source mentions AUR-C109.", 0)  # fmt: skip
    b = gen.generate("q", _context(), "insufficient", checks, respect_check=False)
    assert b.answerable and llm.calls == 1
    empty = gen.generate("q", {"blocks": [], "rendered": ""}, "sufficient")
    assert empty.refused_by == "empty_context" and llm.calls == 1


def test_model_refusal_errors_and_all_unsupported_claims_are_not_answers() -> None:
    no = AnswerGenerator(GenLLM({"answerable": False, "claims": [], "missing": "No date given."}))
    a = no.generate("When?", _context(), "sufficient")
    assert (a.answerable, a.refused_by, a.missing) == (False, "model", "No date given.")
    err = AnswerGenerator(GenLLM(LLMError("timeout"))).generate("q", _context(), "sufficient")
    assert err.refused_by == "error" and "timeout" in err.error
    bad = AnswerGenerator(
        GenLLM(
            {
                "answerable": True,
                "missing": "",
                "claims": [
                    {
                        "text": "AUR-C109 exploded.",
                        "sources": [1],
                        "quote": "exploded",
                        "support": "direct",
                    }
                ],
            }
        )
    )
    c = bad.generate("q", _context(), "sufficient")
    assert not c.answerable and not c.grounded and c.metrics.unsupported == 1 and c.text == ""


def test_stream_emits_validated_claims_then_the_answer() -> None:
    events = list(AnswerGenerator(GenLLM(GOOD)).stream("Why?", _context(), "sufficient"))
    assert [e["type"] for e in events] == ["claim", "claim", "answer"]
    assert events[0]["claim"]["status"] == "verified"
    assert events[-1]["answer"]["grounded"] and events[-1]["answer"]["eval_tokens"] == 40


# ---------------------------------------------------------------- chat service + store
class FakeWorkflow:
    def retrieve(self, question, k=5, filters=None, strategy=None) -> RetrievalResult:
        return RetrievalResult(
            query=question,
            retriever="advanced",
            k=k,
            hits=[],
            latency_ms=50.0,
            details={
                "verdict": "sufficient",
                "checks": [],
                "queries": [question],
                "context": _context(),
                "trace": [{"node": "retrieve", "ms": 30.0}, {"node": "check", "ms": 15.0}],
                "lists": {"dense": {"latency_ms": 20, "embed_ms": 8.0}},
            },
        )


def _service(tmp_path: Path) -> ChatService:
    return ChatService(FakeWorkflow(), AnswerGenerator(GenLLM(GOOD)), ChatStore(tmp_path / "c.db"))


def test_chat_turns_are_stored_with_their_trace(tmp_path: Path) -> None:
    service = _service(tmp_path)
    turn = service.ask("Why did AUR-C103 fail?")
    assert turn["answer"]["grounded"] and turn["timings"]["embedding"] == 8.0
    assert turn["timings"]["retrieve"] == 30.0 and turn["retrieval"]["verdict"] == "sufficient"
    second = service.ask("And its swelling?", conversation_id=turn["conversation_id"])
    conv = service.store.conversation(turn["conversation_id"])
    assert [t["id"] for t in conv["turns"]] == [turn["id"], second["id"]]
    assert conv["title"] == "Why did AUR-C103 fail?"
    assert service.store.conversations()[0]["turns"] == 2
    assert service.store.turn(second["id"])["question"] == "And its swelling?"
    with pytest.raises(LookupError):
        service.ask("q", conversation_id="conv_missing")
    assert service.store.delete_conversation(turn["conversation_id"])
    assert service.store.turn(turn["id"]) is None  # cascade



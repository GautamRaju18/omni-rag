async def test_chat_api_answers_streams_and_lists_history(chat_client) -> None:
    r = await chat_client.post("/api/v1/chat", json={"question": "Why did AUR-C103 fail?"})
    assert r.status_code == 200 and r.json()["answer"]["grounded"]
    conv_id = r.json()["conversation_id"]
    async with chat_client.stream(
        "POST", "/api/v1/chat/stream", json={"question": "Why?", "conversation_id": conv_id}
    ) as s:
        body = "".join([chunk async for chunk in s.aiter_text()])
    kinds = [line[7:] for line in body.splitlines() if line.startswith("event: ")]
    assert kinds == ["start", "retrieval", "claim", "claim", "answer", "done"]
    history = (await chat_client.get("/api/v1/chat/history")).json()
    assert history[0]["id"] == conv_id and history[0]["turns"] == 2
    full = (await chat_client.get(f"/api/v1/chat/history/{conv_id}")).json()
    assert len(full["turns"]) == 2
    missing = await chat_client.post(
        "/api/v1/chat", json={"question": "q", "conversation_id": "conv_nope"}
    )
    assert missing.status_code == 404
    assert (await chat_client.delete(f"/api/v1/chat/history/{conv_id}")).status_code == 204
    assert (await chat_client.get(f"/api/v1/chat/history/{conv_id}")).status_code == 404

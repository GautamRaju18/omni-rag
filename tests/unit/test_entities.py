DOC = "doc_00000000000000bb"


def _el(i: int, content: str, origin: str = "original", confidence: float = 1.0):
    return DocumentElement(
        document_id=DOC, element_id=f"{DOC}-e{i:05d}", element_type=ElementType.PARAGRAPH,
        content=content, source_file="n.txt", order=i, origin=ContentOrigin(origin),
        confidence=confidence, extraction_method=ExtractionMethod.TEXT_DECODE,
    )  # fmt: skip


def _chunk(elements: list[DocumentElement], **kw) -> Chunk:
    return Chunk(
        chunk_id=f"{DOC}-multimodal-256-ctx-00000", document_id=DOC, source_file="n.txt",
        chunking_strategy=ChunkingStrategy.MULTIMODAL, config_id="multimodal-256-ctx",
        chunk_index=0, content="\n\n".join(e.content for e in elements), token_count=50,
        element_type="paragraph", element_ids=[e.element_id for e in elements],
        origins=sorted({e.origin.value for e in elements}),
        context="Document: Notes\nSection: Results", **kw,
    )  # fmt: skip


ELEMENTS = [
    _el(0, "Cell AUR-C103 (electrolyte E-5) failed at cycle 412 at 45 °C."),
    _el(1, "| AUR-C105 | E-7 | 45 | 600 | 89.6 | in_progress | Aiko Tanaka |"),
    _el(2, "Owner: Marco", origin="ocr", confidence=0.87),
    _el(3, "Image description (generated by vlm): the chart shows cell C101.", origin="generated"),
    _el(4, "E-7 replaces the E-5 baseline. Aiko presented the post-mortem for AUR-C103."),
]
CHUNK = _chunk(ELEMENTS)


def _run(entities, relations=()):
    raw = {"entities": [{"name": n, "type": t} for n, t in entities],
           "relations": [dict(zip(("source", "type", "target", "evidence"), r, strict=True))
                         for r in relations]}  # fmt: skip
    return validate_chunk(CHUNK, ELEMENTS, raw)


# ---------------------------------------------------------------- normalisation
def test_norm_and_keys() -> None:
    assert norm("NaPF₆ in **EC:DEC**  (1:1)") == "napf6 in ec:dec (1:1)"
    assert norm("E–7") == "e-7"  # en dash
    assert entity_key("Dr. Priya Raman") == "priya raman"
    assert entity_key("Project Aurora", EntityType.PROJECT) == "aurora"
    assert entity_key("Project Aurora", EntityType.ORGANIZATION) == "project aurora"
    assert entity_key("E-5+FEC") == entity_key("E-5 + FEC") == "e-5 + fec"
    assert entity_id("e-7") == entity_id("e-7") and entity_id("e-7").startswith("ent_")


def test_contains_respects_word_boundaries() -> None:
    assert contains("ec:pc:dmc", "ec") and contains("ec:pc:dmc", "pc")
    assert not contains("replaces dec with pc", "ec")
    assert contains("aur-c103 failed", "aur-c103") and not contains("aur-c1030", "aur-c103")


def test_find_evidence() -> None:
    text = (
        "Gas analysis points to electrolyte\ndecomposition of E-5.\n"
        "| AUR-C101 | E-5 + FEC | 25 | 91.4 | Aiko Tanaka |"
    )
    assert find_evidence("Gas analysis points to electrolyte decomposition of E-5.", text)
    # A table row whose columns the model dropped: tokens in order within one line.
    assert find_evidence("AUR-C101 | 25 | 91.4 | Aiko Tanaka", text).startswith("| aur-c101")
    assert find_evidence("AUR-C101 was tested by Jonas Weber", text) is None
    assert find_evidence("", text) is None


# ---------------------------------------------------------------- entities
def test_entities_are_grounded_and_filtered() -> None:
    mentions, _, rejected = _run([
        ("AUR-C103", "SAMPLE"), ("E-5", "MATERIAL"), ("Aiko Tanaka", "PERSON"),
        ("45 °C", "MATERIAL"), ("in_progress", "MILESTONE"), ("Jonas Weber", "PERSON"),
        ("C101", "SAMPLE"), ("Marco", "PERSON"), ("AUR-C103", "SAMPLE"),
        ("Notes", "DOCUMENT"),  # only in the contextual header, not in the text
    ])  # fmt: skip
    assert [m.key for m in mentions] == ["aur-c103", "e-5", "aiko tanaka", "marco"]
    reasons = {r.item["name"]: r.reason for r in rejected}
    assert reasons == {"45 °C": "measurement", "in_progress": "field_value",
                       "Jonas Weber": "not_in_text", "C101": "generated_only",
                       "Notes": "not_in_text"}  # fmt: skip
    marco = mentions[-1]
    assert marco.origin is ContentOrigin.OCR and marco.confidence == 0.87


def test_schema_violation_rejects_whole_output() -> None:
    mentions, relations, rejected = validate_chunk(CHUNK, ELEMENTS, {"entities": [{"name": 1}]})
    assert (mentions, relations) == ([], [])
    assert rejected[0].kind == "output" and rejected[0].reason.startswith("schema:")


# ---------------------------------------------------------------- relations
ENTS = [("AUR-C103", "SAMPLE"), ("AUR-C105", "SAMPLE"), ("E-5", "MATERIAL"),
        ("E-7", "MATERIAL"), ("Aiko Tanaka", "PERSON")]  # fmt: skip


def test_relation_support_and_direction() -> None:
    _, relations, rejected = _run(ENTS, [
        # stated: verbatim evidence naming both endpoints
        ("E-7", "REPLACES", "E-5", "E-7 replaces the E-5 baseline."),
        # reversed: only fits the other way round (PERSON can't be TESTED_BY's source)
        ("Aiko Tanaka", "TESTED_BY", "AUR-C105", "| AUR-C105 | E-7 | 45 | 600 | Aiko Tanaka |"),
        # person named by first name only in the evidence still counts
        ("AUR-C103", "TESTED_BY", "Aiko Tanaka", "Aiko presented the post-mortem for AUR-C103."),
        # evidence not in the text: kept, but inferred
        ("AUR-C103", "USES", "E-5", "AUR-C103 was built with E-5 electrolyte."),
        # evidence real but names only one endpoint: inferred
        ("AUR-C105", "USES", "E-5", "E-7 replaces the E-5 baseline."),
        ("AUR-C105", "TESTED_BY", "E-7", "x"),  # impossible either way
        ("AUR-C103", "USES", "45 C", "x"),  # endpoint is not an accepted entity
        ("E-5", "RELATED_TO", "E-5", "x"),
    ])  # fmt: skip
    got = {(r.source, r.type.value, r.target): (r.support, r.direction_fixed) for r in relations}
    assert got == {
        ("e-7", "REPLACES", "e-5"): ("stated", False),
        ("aur-c105", "TESTED_BY", "aiko tanaka"): ("stated", True),
        ("aur-c103", "TESTED_BY", "aiko tanaka"): ("stated", False),
        ("aur-c103", "USES", "e-5"): ("inferred", False),
        ("aur-c105", "USES", "e-5"): ("inferred", False),
    }
    unverified = next(
        r for r in relations if r.source == "aur-c103" and r.type is RelationType.USES
    )
    assert unverified.evidence_verified is False and unverified.evidence_origin is None
    assert [r.reason for r in rejected] == ["type_signature", "unknown_endpoint", "self_loop"]


def test_evidence_only_in_generated_text_is_not_stated() -> None:
    elements = [_el(0, "Cells AUR-C101 and AUR-C102."),
                _el(1, "Description: AUR-C101 replaces AUR-C102.", origin="generated")]  # fmt: skip
    chunk = _chunk(elements)
    raw = {"entities": [{"name": "AUR-C101", "type": "SAMPLE"},
                        {"name": "AUR-C102", "type": "SAMPLE"}],
           "relations": [{"source": "AUR-C101", "type": "REPLACES", "target": "AUR-C102",
                          "evidence": "AUR-C101 replaces AUR-C102."}]}  # fmt: skip
    _, (relation,), _ = validate_chunk(chunk, elements, raw)
    assert relation.support == "inferred"
    assert relation.evidence_verified and relation.evidence_origin is ContentOrigin.GENERATED


# ---------------------------------------------------------------- resolution
def test_person_alias_map() -> None:
    full = {"aiko tanaka", "marco lindqvist", "priya raman"}
    got = person_alias_map(full, {"aiko", "a. tanaka", "lindqvist", "jonas"})
    assert got == {"aiko": ("aiko tanaka", "alias:first_name"),
                   "a. tanaka": ("aiko tanaka", "alias:initial"),
                   "lindqvist": ("marco lindqvist", "alias:last_name")}  # fmt: skip
    assert person_alias_map({"marco lindqvist", "marco rossi"}, {"marco"}) == {}  # ambiguous


def _mention(key: str, etype: EntityType = EntityType.PERSON) -> Mention:
    return Mention(key=key, surface=key.title(), type=etype, origin=ContentOrigin.ORIGINAL,
                   confidence=1.0)  # fmt: skip


def test_resolve_document_remaps_mentions_and_relations() -> None:
    rel = Relation(source="aur-c103", target="aiko", type=RelationType.TESTED_BY,
                   support="stated", evidence="x", evidence_verified=True)  # fmt: skip
    chunks = [
        ChunkExtraction(chunk_id="c0", input_sha256="x", mentions=[_mention("aiko tanaka")]),
        ChunkExtraction(chunk_id="c1", input_sha256="x", relations=[rel], mentions=[
            _mention("aiko"), _mention("aur-c103", EntityType.SAMPLE)]),
    ]  # fmt: skip
    resolve_document(chunks)
    aiko = chunks[1].mentions[0]
    assert (aiko.key, aiko.resolution, aiko.surface) == ("aiko tanaka", "alias:first_name", "Aiko")
    assert chunks[1].relations[0].target == "aiko tanaka"


def test_entity_summary_is_order_independent() -> None:
    rows = [{"surface": "Dr. Priya Raman", "type": "PERSON", "document_id": "a"},
            {"surface": "Priya Raman", "type": "PERSON", "document_id": "b"},
            {"surface": "Priya Raman", "type": "ORGANIZATION", "document_id": "b"}]  # fmt: skip
    one, two = entity_summary(rows), entity_summary(list(reversed(rows)))
    assert one == two
    assert one["name"] == "Priya Raman" and one["type"] == "PERSON"
    assert one["types"] == ["PERSON", "ORGANIZATION"] and one["type_counts"] == [2, 1]
    assert one["mention_count"] == 3 and one["document_count"] == 2


# ---------------------------------------------------------------- extractor
def _record() -> DocumentRecord:
    return DocumentRecord(document_id=DOC, source_file="n.txt", file_kind=FileKind.TXT,
                          sha256="0" * 64, size_bytes=1)  # fmt: skip


def _extractor(replies: list[str], calls: list[dict]) -> OllamaExtractor:
    def handler(request: httpx.Request) -> httpx.Response:
        if request.url.path == "/api/tags":
            return httpx.Response(200, json={"models": [{"name": "m", "digest": "abc123"}]})
        calls.append(json.loads(request.content))
        return httpx.Response(200, json={"message": {"content": replies.pop(0)},
                                         "eval_count": 10})  # fmt: skip

    client = httpx.Client(base_url="http://ollama", transport=httpx.MockTransport(handler))
    return OllamaExtractor("http://ollama", "m", client=client)


REPLY = json.dumps({"entities": [{"name": "AUR-C103", "type": "SAMPLE"},
                                 {"name": "E-5", "type": "MATERIAL"}],
                    "relations": [{"source": "AUR-C103", "type": "USES", "target": "E-5",
                                   "evidence": "Cell AUR-C103 (electrolyte E-5)"}]})  # fmt: skip


def test_extractor_validates_and_reuses_unchanged_replies() -> None:
    calls: list[dict] = []
    extractor = _extractor(["not json", REPLY], calls)  # first reply unusable: one retry
    first = extractor.extract_document(_record(), ELEMENTS, [CHUNK], "multimodal-256-ctx")
    assert len(calls) == 2 and calls[0]["format"]["required"] == ["entities", "relations"]
    assert calls[0]["options"]["temperature"] == 0
    assert "TEXT:\nCell AUR-C103" in calls[0]["messages"][1]["content"]
    assert first.model_digest == "abc123" and first.counts()["stated"] == 1

    second = extractor.extract_document(_record(), ELEMENTS, [CHUNK], "multimodal-256-ctx",
                                        previous=first)  # fmt: skip
    assert len(calls) == 2 and extractor.stats["cached"] == 1  # no new model call
    assert second.chunks[0].raw == first.chunks[0].raw

    changed = CHUNK.model_copy(update={"content": CHUNK.content + " More."})
    with pytest.raises(IndexError):  # a changed chunk is sent again (no replies left)
        extractor.extract_document(_record(), ELEMENTS, [changed], "multimodal-256-ctx", first)


def test_extractor_records_unusable_replies() -> None:
    extractor = _extractor(["[]", "{broken"], [])
    result = extractor.extract_document(_record(), ELEMENTS, [CHUNK], "multimodal-256-ctx")
    assert result.chunks[0].error.startswith("unusable model reply")
    assert result.counts()["errors"] == 1 and result.chunks[0].mentions == []


def test_missing_model_is_an_error() -> None:
    client = httpx.Client(base_url="http://o", transport=httpx.MockTransport(
        lambda r: httpx.Response(200, json={"models": []})))  # fmt: skip
    with pytest.raises(ExtractionError, match="not found"):
        _ = OllamaExtractor("http://o", "m", client=client).model_digest


def test_revalidate_uses_stored_replies() -> None:
    extractor = _extractor([REPLY], [])
    stored = extractor.extract_document(_record(), ELEMENTS, [CHUNK], "multimodal-256-ctx")
    stored.chunks[0].mentions, stored.chunks[0].relations = [], []
    again = revalidate(stored, ELEMENTS, [CHUNK])
    assert [m.key for m in again.chunks[0].mentions] == ["aur-c103", "e-5"]
    assert again.chunks[0].relations[0].support == "stated"



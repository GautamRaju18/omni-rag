def test_junk_values_are_rejected() -> None:
    elements = [
        _el(
            0,
            "Category: 400 | Capacity retention (%) | EUR 85,000 | passed | Laminex | EC:DEC (1:1)",
        )
    ]
    raw = {"entities": [{"name": n, "type": "MATERIAL"} for n in
                        ("Category: 400", "Capacity retention (%)", "EUR 85,000", "passed",
                         "Laminex", "EC:DEC (1:1)")]}  # fmt: skip
    mentions, _, rejected = validate_chunk(_chunk(elements), elements, raw)
    assert [m.key for m in mentions] == ["laminex", "ec:dec (1:1)"]  # a ratio is no label
    assert {r.item["name"]: r.reason for r in rejected} == {
        "Category: 400": "field_value", "Capacity retention (%)": "measurement",
        "EUR 85,000": "measurement", "passed": "field_value"}  # fmt: skip


def test_abbreviations_defined_in_the_text_share_a_key() -> None:
    elements = [_el(0, "Decomposition of ethylene carbonate (EC) at 45 °C."),
                _el(1, "EC and PC are solvents.")]  # fmt: skip
    first = _chunk(elements[:1])
    raw = {"entities": [{"name": "ethylene carbonate", "type": "MATERIAL"},
                        {"name": "EC", "type": "MATERIAL"}]}  # fmt: skip
    mentions, _, _ = validate_chunk(first, elements[:1], raw)
    assert [(m.key, m.resolution) for m in mentions] == [("ec", "alias:abbreviation")]
    # A later chunk of the same document that only says "ethylene carbonate" follows suit.
    ec_long = Mention(
        key="ethylene carbonate",
        surface="ethylene carbonate",
        type=EntityType.MATERIAL,
        origin=ContentOrigin.ORIGINAL,
        confidence=1.0,
    )
    later = ChunkExtraction(chunk_id="c1", input_sha256="x", mentions=[ec_long])
    chunks = [ChunkExtraction(chunk_id="c0", input_sha256="x", mentions=mentions), later]
    resolve_document(chunks)
    assert chunks[1].mentions[0].key == "ec"


def test_a_parenthetical_is_not_an_abbreviation() -> None:
    """Regression (2026-11-05): "Cell AUR-C103 (electrolyte E-5)" merged AUR-C103 into E-5."""
    elements = [_el(0, "Cell AUR-C103 (electrolyte E-5) failed at cycle 412.")]
    raw = {"entities": [{"name": "Cell AUR-C103", "type": "SAMPLE"},
                        {"name": "electrolyte E-5", "type": "MATERIAL"}]}  # fmt: skip
    mentions, _, _ = validate_chunk(_chunk(elements), elements, raw)
    assert sorted(m.key for m in mentions) == ["aur-c103", "e-5"]
    assert all(m.resolution is None for m in mentions)


